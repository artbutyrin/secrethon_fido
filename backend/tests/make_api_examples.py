"""Writes example API responses (real Open Targets data, no network) to docs/api/ for the frontend.

Run from the repo root:  python3 -m backend.tests.make_api_examples
"""
import json
import tempfile
from pathlib import Path

from fastapi.testclient import TestClient

import backend.app.api as api
from backend.app.opentargets import OpenTargets

HERE = Path(__file__).resolve().parent
LIVE = HERE / "fixtures" / "live"
OUT = HERE.parents[1] / "docs" / "api"


def recorded_collect(ot, disease_id, target_id):
    return json.loads((LIVE / "runs" / f"{disease_id}__{target_id}.json").read_text())


if __name__ == "__main__":
    import backend.app.pipeline
    from backend.tests.test_step5 import KeywordLLM          # stand-in labels, so the LLM fields are filled
    api.DB_FILE = Path(tempfile.mkdtemp()) / "examples.db"
    api.make_ot = lambda: OpenTargets(LIVE / "cache", offline=True)
    api.make_llm = lambda: KeywordLLM()
    backend.app.pipeline.collect = recorded_collect
    client = TestClient(api.app)
    OUT.mkdir(parents=True, exist_ok=True)

    def save(name, resp):
        (OUT / f"{name}.json").write_text(json.dumps(resp.json(), indent=1, ensure_ascii=False), encoding="utf-8")

    run_id = client.post("/runs", json={"disease": "Alzheimer disease", "target": "BACE1 inhibitor"}).json()["run_id"]
    save("post_runs", client.post("/runs", json={"disease": "familial hypercholesterolemia",
                                                 "target": "anti-PCSK9 antibody", "phase": "ph2"}))
    save("get_run", client.get(f"/runs/{run_id}"))
    save("get_run_claims", client.get(f"/runs/{run_id}/claims"))
    claims = client.get(f"/runs/{run_id}/claims").json()
    save("get_claim_llm", client.get(f"/claims/{next(c['id'] for c in claims if c['origin'] == 'llm')}"))
    save("get_claim_structured", client.get(f"/claims/{next(c['id'] for c in claims if c['fact'] == 'genetic_support')}"))
    save("get_run_result", client.get(f"/runs/{run_id}/result"))
    save("get_run_trials", client.get(f"/runs/{run_id}/trials"))
    amb = client.post("/runs", json={"disease": "AD", "target": "BACE1"}).json()["run_id"]
    save("get_run_ambiguous", client.get(f"/runs/{amb}"))
    save("get_runs", client.get("/runs"))
    save("get_run_report", client.get(f"/runs/{run_id}/report"))
    (OUT / "get_run_report.md").write_text(client.get(f"/runs/{run_id}/report.md").text, encoding="utf-8")
    save("get_facts", client.get("/facts"))

    # step 7: add evidence on PCSK9 (me-too -> Invest), then history
    pcsk9 = client.post("/runs", json={"disease": "familial hypercholesterolemia",
                                       "target": "anti-PCSK9 antibody"}).json()["run_id"]
    save("post_evidence_add", client.post(f"/runs/{pcsk9}/evidence", json={
        "action": "add", "fact": "differentiation_claim", "value": "efficacy", "author": "analyst",
        "source_url": "https://example.org/data-room/phase2-head-to-head.pdf"}))
    save("get_run_history", client.get(f"/runs/{pcsk9}/history"))
    save("post_evidence_refused", client.post(f"/runs/{pcsk9}/evidence", json={
        "action": "add", "fact": "genetic_support", "value": "gwas"}))

    # step 7: confirm an LLM claim that waits for a second source (one sponsor only)
    from backend.tests.test_step7 import OneTrialLLM
    api.make_llm = lambda: OneTrialLLM()
    bace = client.post("/runs", json={"disease": "Alzheimer disease", "target": "BACE1 inhibitor"}).json()["run_id"]
    pending = next(c for c in client.get(f"/runs/{bace}/claims").json() if c["status"] == "pending")
    save("get_claim_pending", client.get(f"/claims/{pending['id']}"))
    save("post_evidence_confirm", client.post(f"/runs/{bace}/evidence", json={
        "action": "confirm", "claim_id": pending["id"], "author": "analyst"}))
    (OUT / "README.md").write_text(
        "# API response examples\n\nGenerated by `backend/make_api_examples.py` from recorded Open Targets responses "
        "(release 26.09). Trial labels come from a keyword stand-in for the LLM and the report uses template text "
        "(no LLM), so wording differs from a real model; the structure is the same. The schema of every endpoint is at `/docs` when the server runs.\n", encoding="utf-8")
    print(f"written: {sorted(p.name for p in OUT.iterdir())}")
