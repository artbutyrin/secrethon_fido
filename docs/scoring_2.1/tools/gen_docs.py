"""Regenerate docs/FACTS.md, docs/RULES.md and docs/facts_catalog.json from the built-in configuration."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import unobio_scoring as U  # noqa: E402
from unobio_scoring.engine import facts_in  # noqa: E402

cfg = U.load_config()
V11 = U.load_config(fixes=False)
OPS = {"eq": "=", "ne": "≠", "ge": "≥", "gt": ">", "le": "≤", "lt": "<", "in": "∈"}


def text(c):
    if "all" in c:
        return "(" + " AND ".join(text(x) for x in c["all"]) + ")"
    if "any" in c:
        return "(" + " OR ".join(text(x) for x in c["any"]) + ")"
    if "not" in c:
        return "NOT " + text(c["not"])
    if "known" in c:
        return f"{c['fact']} {'known' if c['known'] else 'unknown'}"
    op = next(k for k in OPS if k in c)
    v = c[op]
    v = v["fact"] if isinstance(v, dict) else json.dumps(v, ensure_ascii=False)
    d = f" [unknown → {json.dumps(c['default'])}]" if "default" in c else ""
    return f"{c['fact']} {OPS[op]} {v}{d}"


used = {}
for it in cfg.items.values():
    if it["id"] not in cfg.variant_items():
        continue
    for k in ("red", "green", "strong_green"):
        for f in facts_in(it.get(k, {})):
            used.setdefault(f, set()).add(f"item:{it['id']}")
    for f in it.get("evidence_facts") or []:
        used.setdefault(f, set()).add(f"item:{it['id']}")
for r in cfg.rules:
    for f in facts_in(r["when"]):
        used.setdefault(f, set()).add(f"rule:{r['id']}")
for c in cfg.raw.get("caps", []):
    for f in facts_in(c["when"]):
        used.setdefault(f, set()).add(f"cap:{c['id']}")

cat = U.fact_catalog(cfg)
new = set(cfg.facts) - set(V11.facts)
lines = ["# Facts the scorer accepts", "",
         f"Generated by tools/gen_docs.py from unobio_scoring {cfg.raw['version']}. {len(cfg.facts)} facts "
         f"({len(new)} new in 2.1, marked ★). Any fact may be missing: unknown never counts as negative.", "",
         "Columns: **level** — mechanism (disease + target, from open data) or asset (this drug, mostly a human / "
         "data room); **MVP source** — where the pipeline gets it now (`none` = only from a person); **critical** — "
         "values that alone give a kill (K) or a strong minus / red item (S).", ""]
for scope in ("mechanism", "asset"):
    lines += [f"## {scope.title()}-level facts", "",
              "| Fact | Type / values | MVP source | Critical | Used by | Meaning; where to get it |", "|---|---|---|---|---|---|"]
    for name, spec in cfg.facts.items():
        if spec["scope"] != scope:
            continue
        e = cat[name]
        tv = spec["type"] + (": " + ", ".join(map(str, e["values"])) if "values" in e and spec["type"] == "enum" else "")
        if spec["type"] in ("int", "number"):
            tv += f" {spec.get('min', 0)}–{spec.get('max') if spec.get('max') is not None else '∞'}"
        crit = ", ".join(f"{k}→{'K' if t == 'kill' else 'S'}" for k, t in e["critical_values"].items()) or "—"
        use = ", ".join(sorted(used.get(name, []))) or "—"
        lines.append(f"| `{name}`{' ★' if name in new else ''} | {tv} | {spec.get('mvp', 'none')} | {crit} | {use} | "
                     f"{spec['label']}. {spec.get('source', '')}"
                     + (f" **DD:** {spec['dd']}" if spec.get("dd") else "") + " |")
    lines.append("")
(ROOT / "docs" / "FACTS.md").write_text("\n".join(lines) + "\n")
(ROOT / "docs" / "facts_catalog.json").write_text(json.dumps(cat, indent=1, ensure_ascii=False, default=str))

r = ["# Scorecard, rules and caps", "", f"Generated from unobio_scoring {cfg.raw['version']}.", "",
     "## Scorecard (8 items)", "", "| Item | Axis | Level | Red if | Green if | Strong green (2 pluses) if |",
     "|---|---|---|---|---|---|"]
for iid in cfg.variant_items():
    it = cfg.items[iid]
    r.append(f"| {it['name']} | {it['axis']}{' (mechanism evidence)' if it.get('mechanism_evidence') else ''} | "
             f"{it['scope']} | {text(it['red']) if 'red' in it else '—'} | {text(it['green']) if 'green' in it else '—'} | "
             f"{text(it['strong_green']) if 'strong_green' in it else '—'} |")
old_ids = {x["id"]: x for x in V11.rules}
r += ["", "## Rules", "", "Kill: Do Not Invest at once. Strong: 2 minuses. Warning: 1 minus. In one cluster only the "
      "strongest counts. ★ new or changed in 2.1.", "", "| Rule | Tier | Cluster | Fires when |", "|---|---|---|---|"]
for x in cfg.rules:
    star = " ★" if x["id"] not in old_ids or old_ids[x["id"]] != x else ""
    r.append(f"| {x['name']} (`{x['id']}`){star} | {x['tier']} | {x.get('cluster') or '—'} | {text(x['when'])} |")
r += ["", "## Caps (verdict cannot exceed Conditional)", "", "| Cap | When | Reason |", "|---|---|---|"]
r += [f"| `{c['id']}` ({c['finding']}) | {text(c['when'])} | {c['reason']} |" for c in cfg.raw["caps"]]
th = cfg.thresholds
r += ["", "## Verdict thresholds", "", "```", json.dumps({k: v for k, v in th.items()}, indent=1), "```", "",
      "Order: kill → DNI; minuses ≥ neg_dni → DNI; net ≥ invest_margin with science pluses ≥ min_science_pos_invest "
      "and a mechanism green → Invest (then caps); net ≤ dni_margin → DNI; otherwise Conditional / DNI by "
      "min_pos_conditional and the mechanism requirement."]
(ROOT / "docs" / "RULES.md").write_text("\n".join(r) + "\n")
print("docs written")
